/* Banner zum Einführungspreis ganz oben in Ratgeber und Seite für Fensterbauer, so wie Startseite und App es zeigen (gemeinsam.js
   EinfBanner, Gestalt in gemeinsam.css). Mit Countdown, gerechnet beim Ausliefern; ab dem Stichtag kommt es nicht mehr dazu */
const geld = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace('.', ',')) + '&nbsp;€';
export function banner(pfad, env) {
  const tage = Math.max(1, Math.ceil((Date.parse(EINFUEHRUNG.ende) - jetztAus(env)) / 864e5)), rest = tage <= 1 ? 'Nur noch heute' : 'Noch ' + tage + ' Tage';
  const [, m, t] = EINFUEHRUNG.bis.split('-').map(Number), bis = t + '. ' + ['Januar', 'Februar', 'März', 'April', 'Mai', 'Juni', 'Juli', 'August', 'September', 'Oktober', 'November', 'Dezember'][m - 1];
  const v = EINFUEHRUNG.vorher, d = EINFUEHRUNG.danach, betrieb = pfad.startsWith('/fuer-fensterbauer/');
  const text = betrieb
    ? '<b>Einführungspreise bis ' + bis + ':</b> Abo 10 für ' + geld(v.abo) + ', Plus für ' + geld(v.plus) + ' im Monat <span class="spaeter">· danach ' + geld(d.abo) + ' und ' + geld(d.plus) + '</span>'
    : '<b>Einführungspreis bis ' + bis + ':</b> Aufmaßblatt ' + geld(v.aufmass) + ' <span class="spaeter">· danach ' + geld(d.aufmass) + '</span>';
  return '<a class="einf-bar" href="' + (betrieb ? '/#fensterbauer' : '/app/') + '"><span><span class="txt">' + text + '</span><span class="rest">' + rest + '</span><span class="los">' + (betrieb ? 'Preise ansehen' : 'Jetzt ausmessen') + ' →</span></span></a>';
}
const mitBanner = (html, pfad, env) => (BANNER_SEITEN.test(pfad) && konfig(env).einfuehrung ? html.replace(/<body[^>]*>/, (m) => m + '\n' + banner(pfad, env)) : html);

/* Canonical und og:url zusätzlich im HTML: Bing und KI-Crawler lesen die Seite selbst, nicht immer die Kopfzeilen */
export function kopf(html, kan) {
  const neu = (/<link rel="canonical"/.test(html) ? '' : '<link rel="canonical" href="' + kan + '">\n') +
    (/property="og:url"/.test(html) || !/property="og:title"/.test(html) ? '' : '<meta property="og:url" content="' + kan + '">\n');
  return neu && html.includes('</head>') ? html.replace('</head>', () => neu + '</head>') : html; // als Funktion: „$“ in einer Adresse bleibt, wie es ist
}

/* IndexNow (indexnow.org): geänderte Seiten an Bing und die anderen Teilnehmer melden (Yandex, Seznam, Naver u. a.), damit sie schnell
   neu gelesen werden; Bing ist die Grundlage von Copilot. Der Schlüssel ist öffentlich und liegt als Datei web/<Schlüssel>.txt.
   Gemeldet wird beim täglichen Lauf (worker.js → scheduled → geplant), nur mit Freigabe (INDEXIERUNG=1) und nur Seiten, deren
   stand höchstens zwei Tage zurückliegt: nach einer Veröffentlichung also zwei- bis dreimal, sonst nie. */
export const INDEXNOW = 'f39851a897e004d2371f5b99367aa8c2';
export const HAUPTADRESSE = 'https://eeziframes.com';
export async function indexnow(env, holen, jetzt) {
  if (!env || String(env.INDEXIERUNG || '') !== '1') return { ok: true, gemeldet: 0, grund: 'nicht freigegeben' };
  const b = String(env.KANONISCH || HAUPTADRESSE).replace(/\/+$/, ''), heute = Date.parse((jetzt || new Date()).toISOString().slice(0, 10));
  const neu = SEITEN.filter((x) => { const t = (heute - Date.parse(x.stand || STAND)) / 864e5; return t >= 0 && t <= 2; }).map((x) => b + x.pfad);
  if (!neu.length) return { ok: true, gemeldet: 0 };
  const r = await (holen || fetch)('https://api.indexnow.org/indexnow', {
    method: 'POST', headers: { 'content-type': 'application/json; charset=utf-8' },
    body: JSON.stringify({ host: new URL(b).host, key: INDEXNOW, keyLocation: b + '/' + INDEXNOW + '.txt', urlList: neu })
  });
  return { ok: r.ok, status: r.status, gemeldet: neu.length };
}

